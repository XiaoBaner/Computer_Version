#!/usr/bin/env python3
"""Generate several takes of one line from a clone reference, then keep them all.

The clone backend is sampling, not deterministic: the same reference and the same
text give different prosody and different mistakes every seed. When one take is
all you get, "sounds robotic" is really "this particular sample was robotic" —
so produce a spread and choose, instead of tuning a parameter forever.

Writes `<out-dir>/<tag>-take{NN}.wav` plus `takes.json` with per-take numbers.

Usage:
  python3 tools/voice/gen_clone_takes.py \
    --ref-audio assets/voice/refs/sucaiB/ref-B.wav \
    --ref-text "苦情树下，以相爱者的妖力与记忆起誓，可成转世续缘之法。" \
    --text "今天也辛苦了，要不要先休息一下？" \
    --takes 4 --seed0 11 --out-dir assets/voice/demos/sucaiB/takes
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model-dir", type=Path,
                    default=Path.home() / ".cache/modelscope/models/Qwen--Qwen3-TTS-12Hz-1.7B-Base/snapshots/master")
    ap.add_argument("--ref-audio", required=True, type=Path)
    ap.add_argument("--ref-text", required=True)
    ap.add_argument("--text", required=True)
    ap.add_argument("--tag", default="take")
    ap.add_argument("--takes", type=int, default=4)
    ap.add_argument("--seed0", type=int, default=11)
    ap.add_argument("--temperature", type=float, default=0.75)
    ap.add_argument("--top-p", type=float, default=0.9)
    ap.add_argument("--top-k", type=int, default=50)
    ap.add_argument("--rep-penalty", type=float, default=1.05)
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--device", default="mps")
    ap.add_argument("--x-vector-only", action="store_true",
                    help="clone the timbre only; prosody is generated by the model, not copied from the reference")
    args = ap.parse_args()

    import soundfile as sf
    import torch
    from qwen_tts import Qwen3TTSModel

    model = Qwen3TTSModel.from_pretrained(str(args.model_dir), dtype=torch.bfloat16, low_cpu_mem_usage=True)
    model.model.to(args.device)
    model.model.eval()
    model.device = torch.device(args.device)
    print("model loaded", flush=True)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    records = []
    for i in range(args.takes):
        seed = args.seed0 + i
        torch.manual_seed(seed)
        t0 = time.time()
        wavs, sr = model.generate_voice_clone(
            text=args.text,
            language="Chinese",
            ref_audio=str(args.ref_audio),
            ref_text=args.ref_text,
            x_vector_only_mode=args.x_vector_only,
            non_streaming_mode=True,
            temperature=args.temperature,
            top_p=args.top_p,
            top_k=args.top_k,
            repetition_penalty=args.rep_penalty,
        )
        y = wavs[0]
        name = f"{args.tag}-take{seed:02d}.wav"
        sf.write(str(args.out_dir / name), y, sr)
        rec = {"file": name, "seed": seed, "dur": round(len(y) / sr, 2),
               "gen_s": round(time.time() - t0, 1)}
        records.append(rec)
        print(f"  {name}  {rec['dur']}s  ({rec['gen_s']}s)", flush=True)

    (args.out_dir / "takes.json").write_text(
        json.dumps({"text": args.text, "ref_audio": str(args.ref_audio), "records": records},
                   ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(records)} takes to {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
